/// API returns `content` as a string + optional `metadata.modelName`.
/// We use [content] as the canonical text. [attachments] is for future
/// image/file additions (mobile API doesn't return parts/attachments today).
@freezed
class MessageModel with _$MessageModel {
  const factory MessageModel({
    @Default('') String id,
    @Default('') String chatId,
    @Default('user') String role,
    @Default('') String content,
    String? modelName,
    @Default([]) List<MessageAttachment> attachments,
    DateTime? createdAt,
    /// Client-only flag — true if this is a failed-send placeholder so the
    /// UI can render it as a retry-able failure bubble instead of a real
    /// assistant reply. Server never sends this.
    @Default(false) bool isError,
    /// Client-only — original user text we'd resend on retry. Set on failed
    /// assistant placeholders so the bubble's retry button knows what to send.
    String? retryText,
  }) = _MessageModel;

  factory MessageModel.fromJson(Map<String, dynamic> json) =>
      _$MessageModelFromJson(json);

  /// Persisted messages carry the model under `metadata.modelName`; lift it to
  /// the top level so the "generated by <model>" badge shows on history too.
  static Map<String, dynamic> normalize(Map<dynamic, dynamic> raw) {
    final m = Map<String, dynamic>.from(raw);
    final meta = m['metadata'];
    if (m['modelName'] == null && meta is Map && meta['modelName'] != null) {
      m['modelName'] = meta['modelName'];
    }
    return m;
  }
}

