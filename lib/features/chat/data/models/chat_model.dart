@freezed
class MessagesResponse with _$MessagesResponse {
  const factory MessagesResponse({
    @Default([]) List<MessageModel> messages,
    String? nextCursor,
    @Default(false) bool hasMore,
  }) = _MessagesResponse;

  // Constructs directly: real response is `{messages, hasMore, cursor:{before,
  // after}}`. We surface `cursor.before` (the oldest id on this page) as
  // nextCursor — the id to send back as `before` to load older messages.
  factory MessagesResponse.fromJson(Map<String, dynamic> json) {
    final rawMsgs = json['messages'];
    final messages = <MessageModel>[];
    if (rawMsgs is List) {
      for (final e in rawMsgs) {
        if (e is Map) {
          try {
            messages.add(MessageModel.fromJson(MessageModel.normalize(e)));
          } catch (_) {/* skip malformed row */}
        }
      }
    }
    final cursor = json['cursor'];
    final before = cursor is Map ? cursor['before'] : null;
    return MessagesResponse(
      messages: messages,
      nextCursor:
          before is String ? before : json['nextCursor'] as String?,
      hasMore: json['hasMore'] is bool ? json['hasMore'] as bool : false,
    );
  }
}

@freezed
class StreamEvent with _$StreamEvent {
  const factory StreamEvent.start({
    required String messageId,
    String? model,
    /// "resume" when the stream is a continuation of a truncated turn.
    /// `null` for a normal new turn.
    String? mode,
  }) = StreamEventStart;

  const factory StreamEvent.token({
    required String content,
  }) = StreamEventToken;

  const factory StreamEvent.usage({
    required int inputTokens,
    required int outputTokens,
    required int totalTokens,
  }) = StreamEventUsage;

  /// Server-assigned id of the assistant turn that just finished. Same id
  /// across `start` and `done`. Needed to call `/complete/resume` and to
  /// target the existing bubble during a resume stream-append.
  ///
  /// `finishReason` per OpenAI semantics: "stop" | "length" | "unknown".
  /// `truncated` is the single boolean signal driving the Continue button —
  /// equals `finishReason == 'length'` server-side.
  const factory StreamEvent.done({
    String? messageId,
    String? finishReason,
    @Default(false) bool truncated,
    /// "resume" if this `done` closes a resume stream rather than a fresh turn.
    String? mode,
  }) = StreamEventDone;

  const factory StreamEvent.error({
    required String message,
    String? code,
  }) = StreamEventError;

  /// Informational status events emitted by the backend auto web-search
  /// pipeline. Three variants today:
  ///   - status="web-searching"        + query + reason
  ///   - status="web-searched"         + resultCount + source
  ///   - status="web-search-no-results"
  /// Future status types (deep-thinking, tool-running, ...) flow through
  /// the same StreamEventStatus event — match on `status` not type.
  const factory StreamEvent.status({
    required String status,
    String? query,
    String? reason,
    int? resultCount,
    String? source,
  }) = StreamEventStatus;

  factory StreamEvent.fromJson(Map<String, dynamic> json) {
    // Sahachiel: read every field type-safely. The /complete NDJSON stream can
    // carry a wrong-typed field - the backend confirmed `code` sometimes arrives
    // as a number, not a string. A blanket `as String?` throws on that and kills
    // the parse of the whole event (and, depending on the caller, the stream).
    // `str()` returns null on a non-string instead of throwing; numeric counts
    // are coerced via num. Same defensive approach as the HTTP _envelope fix.
    String? str(String key) {
      final v = json[key];
      return v is String ? v : null;
    }

    final usage = json['usage'];
    int usageInt(String key) =>
        (usage is Map && usage[key] is num) ? (usage[key] as num).toInt() : 0;

    return switch (str('type')) {
      'start' => StreamEvent.start(
          // messageId may be absent on some backend variants — don't blow up
          // the whole stream just because the start event is half-shaped.
          messageId: str('messageId') ?? '',
          model: str('model'),
          mode: str('mode'),
        ),
      'token' => StreamEvent.token(content: str('content') ?? ''),
      'usage' => StreamEvent.usage(
          inputTokens: usageInt('inputTokens'),
          outputTokens: usageInt('outputTokens'),
          totalTokens: usageInt('totalTokens'),
        ),
      'done' => StreamEvent.done(
          messageId: str('messageId'),
          finishReason: str('finishReason'),
          truncated: json['truncated'] is bool ? json['truncated'] as bool : false,
          mode: str('mode'),
        ),
      'status' => StreamEvent.status(
          status: str('status') ?? '',
          query: str('query'),
          reason: str('reason'),
          resultCount:
              json['resultCount'] is num ? (json['resultCount'] as num).toInt() : null,
          source: str('source'),
        ),
      'error' => StreamEvent.error(
          message: str('message') ?? str('error') ?? 'Unknown error',
          code: str('code'),
        ),
      _ => StreamEvent.error(message: 'Unknown event type: ${json['type']}'),
    };
  }
}
